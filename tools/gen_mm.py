#!/usr/bin/env python3
"""Writes data/languages/tms34010_mm.sinc: MMTM/MMFM register-list tables and CLR.

MMTM's list word has R0 in bit 15; registers are stored R0 first, each after a pre-decrement of
the pointer by 32. MMFM's list word has R0 in bit 0; registers are loaded R15 first, each followed
by a post-increment by 32. A15/B15 is SP. Each list bit is a subtable that matches the pointer
register's file (rf) itself, so the p-code names the registers directly.

  tools/gen_mm.py > data/languages/tms34010_mm.sinc
"""

def reg(f, i):
    return 'SP' if i == 15 else f'{f}{i}'


out = ['# Generated by tools/gen_mm.py: MMTM/MMFM register lists and CLR. Do not edit.', '',
       '# The list subtables match the list word; the pointer register is copied to MMP.']
for f in 'AB':
    for i in range(16):
        t = f'mt{f}{i}'
        b = f'l{15 - i}'
        out.append(f'{t}: ",{reg(f, i)}" is {b}=1 {{ MMP = MMP - 32; *:4 (MMP >> 3) = {reg(f, i)}; }}')
        out.append(f'{t}: "" is {b}=0 {{ }}')
    for i in range(16):
        t = f'mf{f}{i}'
        b = f'l{i}'
        out.append(f'{t}: ",{reg(f, i)}" is {b}=1 {{ {reg(f, i)} = *:4 (MMP >> 3); MMP = MMP + 32; }}')
        out.append(f'{t}: "" is {b}=0 {{ }}')
out.append('')
# If the pointer register is itself in the list, the copy in MMP is what is stored or
# advanced (MMTM stores the decremented pointer, MMFM's loaded value is then advanced), as in
# MAME; the register is written back from MMP at the end unless MMFM loaded it.
for f, rf in (('A', 0), ('B', 1)):
    mt = ' & '.join(f'mt{f}{i}' for i in range(16))
    mf = ' & '.join(f'mf{f}{i}' for i in range(16))
    out.append(f':MMTM Rd^' + '^'.join(f'mt{f}{i}' for i in range(16)) + f' is op11=0x04c & rf={rf} & Rd; {mt} {{')
    out.append('\tmmtm_flags(Rd); MMP = Rd; ' + ' '.join(f'build mt{f}{i};' for i in range(16)) + ' Rd = MMP;')
    out.append('}')
    out.append(f':MMFM Rd^' + '^'.join(f'mf{f}{i}' for i in range(16)) + f' is op11=0x04d & rf={rf} & Rd; {mf} {{')
    out.append('\tMMP = Rd; ' + ' '.join(f'build mf{f}{i};' for i in range(15, -1, -1)) + ' Rd = MMP;')
    out.append('}')
out.append('')
out.append('# XOR Rd,Rd is shown as CLR Rd (as TI\'s assembler and MAME do)')
for i in range(16):
    out.append(f':CLR Rd is op7=0x2b & rsi={i} & rdi={i} & Rd {{ Rd = 0; Z = 1; }}')
print('\n'.join(out))
